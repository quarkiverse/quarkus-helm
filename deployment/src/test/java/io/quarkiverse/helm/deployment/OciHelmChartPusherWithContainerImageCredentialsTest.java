package io.quarkiverse.helm.deployment;

import static io.quarkiverse.helm.deployment.OciHelmChartPusherTest.createChartTarball;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.File;
import java.nio.file.Path;
import java.util.Optional;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.testcontainers.containers.GenericContainer;
import org.testcontainers.images.builder.Transferable;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import land.oras.ContainerRef;
import land.oras.Manifest;
import land.oras.Registry;
import land.oras.utils.Const;

/**
 * Pushes to an OCI registry that requires authentication, configuring only the container image credentials.
 */
@Testcontainers(disabledWithoutDocker = true)
class OciHelmChartPusherWithContainerImageCredentialsTest {

    private static final String USERNAME = "user";
    private static final String PASSWORD = "secret";
    // bcrypt hash of `user:secret`, as generated by `htpasswd -Bbn user secret`
    private static final String HTPASSWD = "user:$2y$05$oZNDFTm5SYGq/07GwpvFc.0IpjLgO5JyKmEVwHIdyDfvBJ0gT5rH.";

    @Container
    static final GenericContainer<?> REGISTRY = new GenericContainer<>("registry:2")
            .withExposedPorts(5000)
            .withCopyToContainer(Transferable.of(HTPASSWD), "/auth/htpasswd")
            .withEnv("REGISTRY_AUTH", "htpasswd")
            .withEnv("REGISTRY_AUTH_HTPASSWD_REALM", "test")
            .withEnv("REGISTRY_AUTH_HTPASSWD_PATH", "/auth/htpasswd");

    @TempDir
    Path tempDir;

    @Test
    void pushesUsingTheContainerImageCredentialsForTheSameRegistry() throws Exception {
        File tarball = createChartTarball(tempDir, "myapp", "1.0.0");
        ContainerImageRegistry containerImage = ContainerImageRegistryTest.containerImage(Optional.of(registryAddress()),
                Optional.of(USERNAME), Optional.of(PASSWORD), true);

        HelmChartUploader.pushToHelmRepository(tarball,
                containerImage.applyDefaultsTo(helmRepository("oci://" + registryAddress() + "/charts")));

        Registry registry = Registry.builder().defaults(USERNAME, PASSWORD).withInsecure(true).build();
        Manifest manifest = registry.getManifest(ContainerRef.parse(registryAddress() + "/charts/myapp:1.0.0"));
        assertEquals(Const.HELM_CONTENT_MEDIA_TYPE, manifest.getLayers().get(0).getMediaType());
    }

    @Test
    void failsWithoutCredentials() throws Exception {
        File tarball = createChartTarball(tempDir, "myapp", "1.0.0");
        // the container image is pushed to another registry, so its credentials must not be used
        ContainerImageRegistry containerImage = ContainerImageRegistryTest.containerImage(Optional.of("quay.io"),
                Optional.of(USERNAME), Optional.of(PASSWORD), true);

        RuntimeException e = assertThrows(RuntimeException.class, () -> HelmChartUploader.pushToHelmRepository(tarball,
                containerImage.applyDefaultsTo(helmRepository("oci://" + registryAddress() + "/charts"))));
        assertTrue(e.getMessage().contains("Couldn't push the Helm chart to the OCI registry"), e.getMessage());
    }

    private static String registryAddress() {
        return REGISTRY.getHost() + ":" + REGISTRY.getMappedPort(5000);
    }

    private static HelmRepository helmRepository(String url) {
        // no username/password: they can only come from the container image configuration
        return HelmChartUploaderTest.repository(HelmRepositoryType.OCI, url, null, null);
    }
}
